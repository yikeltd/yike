#!/usr/bin/env node
/**
 * Write .env.e2e.local for a non-production Supabase project (never commit output).
 * Requires: supabase CLI logged in, project already created and migrated.
 *
 * Usage:
 *   node scripts/provision-isolated-e2e-env.mjs --ref <project-ref>
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const PRODUCTION_REF = "hlpojfurfldvcxfxhveg";
const RETIRED_REF = "gyxemepnrkwxocgzfbeo";
const DEFAULT_OTP = "f7a141a77373cee893c932f3515700e3105a874b5ecfea9bf2969f6b6d020a7b";

function parseRef(argv) {
  const i = argv.indexOf("--ref");
  if (i >= 0 && argv[i + 1]) return argv[i + 1].trim().toLowerCase();
  const env = process.env.E2E_EXPECTED_REF?.trim().toLowerCase();
  if (env) return env;
  console.error("Usage: node scripts/provision-isolated-e2e-env.mjs --ref <non-production-ref>");
  process.exit(1);
}

function main() {
  const ref = parseRef(process.argv);
  if (ref === PRODUCTION_REF || ref === RETIRED_REF) {
    console.error("Ref must not be production or retired sandbox.");
    process.exit(1);
  }

  const raw = execSync(`supabase projects api-keys --project-ref ${ref} -o json`, {
    encoding: "utf8",
  });
  const keys = JSON.parse(raw);
  const anon = keys.find((k) => k.name === "anon")?.api_key;
  const service = keys.find((k) => k.name === "service_role")?.api_key;
  if (!anon || !service) {
    console.error("Could not resolve anon/service_role keys from Supabase CLI.");
    process.exit(1);
  }

  const url = `https://${ref}.supabase.co`;
  const body = `# Generated by scripts/provision-isolated-e2e-env.mjs — do not commit
E2E_EXPECTED_REF=${ref}

NEXT_PUBLIC_SUPABASE_URL=${url}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}
SUPABASE_URL=${url}
SUPABASE_SERVICE_ROLE_KEY=${service}

YIKE_OTP_SERVER_TOKEN=${DEFAULT_OTP}

APP_ENV=development
YIKE_PIN_PEPPER=local-e2e-pin-pepper-minimum-32-characters

E2E_EPHEMERAL_AUTH=1
`;

  const out = join(root, ".env.e2e.local");
  writeFileSync(out, body, { mode: 0o600 });
  console.log(`Wrote ${out} for ref ${ref} (secrets not printed).`);
  console.log("Next: npm run verify:e2e-supabase && npm run e2e:nav-prereqs:isolated");
}

main();
